package com.hughcode;

public class Album {

    String name;
    String artist;
    String img_url;
    String release_date;

    public Album(String name, String artist, String img_url, String release_date) {
        this.name = name;
        this.artist = artist;
        this.img_url = img_url;
        this.release_date = release_date;
    }
}

